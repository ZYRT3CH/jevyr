import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import unicodeLengthModule from 'ajv/dist/runtime/ucs2length.js';
import { writeFile } from 'node:fs/promises';
import { CASE_SUBMISSION_TYPEBOX } from '../src/submission-schema.ts';

// Build-time compilation avoids eval/new Function in browser and Worker clients.
const ajv = new Ajv2020({ strict: true, allErrors: true, coerceTypes: false, useDefaults: false, removeAdditional: false, ownProperties: true, code: { source: true, esm: true } });
const validate = ajv.compile(CASE_SUBMISSION_TYPEBOX);
const unicodeLength = unicodeLengthModule.default ?? unicodeLengthModule;
const generated = '// @ts-nocheck\n// Generated by scripts/compile-case-schema.mjs from the shared TypeBox schema. Do not edit.\n// Includes Ajv MIT-licensed Unicode length helper, inlined for browser/Worker compatibility.\n' + standaloneCode(ajv, validate).replaceAll('require("ajv/dist/runtime/ucs2length").default', `(${unicodeLength.toString()})`) + '\n';
await writeFile(new URL('../src/generated-case-validator.ts', import.meta.url), generated);
